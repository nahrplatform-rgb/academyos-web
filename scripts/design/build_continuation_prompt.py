"""Generate the copyable continuation prompt from the authoritative tracker."""
import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TRACKER = ROOT / 'docs/06-delivery/experience-execution.csv'
OUTPUT = ROOT / 'docs/06-delivery/continue-academyos.md'


def render(rows):
    intro = """# AcademyOS continuation prompt

Generated from `experience-execution.csv`. Do not edit this file directly. Regenerate after every checkpoint with `python3 scripts/design/build_continuation_prompt.py`; the execution validator rejects stale output. This is a continuation instruction, not new policy or access authorization.

Copy the following prompt into the implementation chat:

---

Continue AcademyOS in `/Users/moamenghareeb/AcademyOS`.

Read `AGENTS.md`, `docs/06-delivery/experience-execution.md`, the current `docs/06-delivery/experience-execution.csv`, and the evidence linked by the relevant row before acting. Repository records govern; recheck source, working tree and live release rather than assuming the snapshot below is current. Preserve completed work and concurrent changes.

Follow the unfinished tracked sequence, without restarting completed checkpoints. Current Owner priority within EX-02 is visible task continuity across Home → Calendar → session → Back, investigating EX-04 dependencies where necessary. Measure visible loading, content disappearance, repeated requests and lost return context; choose the next bounded change from that evidence. Remaining individual-date planning listener work supports this journey but fewer requests alone do not establish a smoother experience. Once this priority is evidenced, continue the remaining tracker actions and dependencies.

Preserve current server authorization, tenant scope, dirty input, exact-change review and original unknown-operation recovery. No unapproved private stale-display TTL, persistence, offline queue, telemetry or access restoration. Do not substitute styling or new features for navigation/loading work.

Measure before/after behavior and request ownership. Verify EN/AR navigation, return, refresh, denied/failure, dirty and unknown states as applicable. Maintain the factual HTML/captures, traceability and evidence. Keep design, implementation, local tests, deployment, hosted verification, Owner acceptance and independent security separate; do not close findings from deployment alone. Report visible improvements separately from request reductions and unresolved measurements.

After each checkpoint, update the tracker and evidence, regenerate this prompt, and run `python3 scripts/design/validate_experience_execution.py` plus the affected documentation/review checks. If blocked, record the exact blocker and safe next action without inventing approval or marking the work complete. Keep all unfinished batches visible.

## Tracker snapshot

"""
    fields = [('implementation_status', 'Implementation'), ('local_status', 'Local checks'),
              ('deployment_status', 'Deployment'), ('hosted_status', 'Hosted verification'),
              ('owner_acceptance_status', 'Owner acceptance'), ('independent_security_status', 'Independent security'),
              ('next_action', 'Next action'), ('evidence', 'Evidence')]
    blocks = []
    for row in rows:
        lines = [f"### {row['work_id']} — {row['scope']}", '',
                 f"Dependencies: {row['dependencies'] or 'none declared'}.",
                 f"Findings: {row['finding_ids']}.", f"Design: {row['design_status']}.", '']
        lines += [f"- {label}: {row[key]}" for key, label in fields]
        blocks.append('\n'.join(lines))
    return intro + '\n\n'.join(blocks) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    with TRACKER.open(newline='') as stream:
        expected = render(list(csv.DictReader(stream)))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit('FAIL: continuation prompt stale; run python3 scripts/design/build_continuation_prompt.py')
        print('PASS: continuation prompt matches the execution tracker')
    else:
        OUTPUT.write_text(expected)
        print(f'Updated {OUTPUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
