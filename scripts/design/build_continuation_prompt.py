"""Generate the copyable continuation prompt from the authoritative tracker."""
import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TRACKER = ROOT / 'docs/06-delivery/experience-execution.csv'
OUTPUT = ROOT / 'docs/06-delivery/continue-academyos.md'


def execution_route(rows):
    """Choose only an explicit tracker priority, never the first unfinished ID."""
    if not rows:
        raise ValueError('Execution tracker is empty')
    allowed_states = {'current', 'queued', 'supporting', 'retained', 'checkpoint_passed'}
    lanes = {'baseline', 'primary', 'supporting'}
    seen = set()
    for row in rows:
        if row.get('execution_lane') not in lanes or row.get('execution_state') not in allowed_states:
            raise ValueError(f"Invalid execution routing for {row.get('work_id')}")
        order = row.get('execution_order', '')
        if not order.isdecimal():
            raise ValueError('Execution order must be a nonnegative integer')
        pair = (row['execution_lane'], int(order))
        if pair in seen or not row.get('dependency_gate', '').strip():
            raise ValueError('Duplicate lane/order or missing scoped dependency gate')
        seen.add(pair)
        if row['execution_lane'] == 'primary':
            if row['execution_state'] not in {'current', 'queued', 'checkpoint_passed'}:
                raise ValueError('Primary work needs a current, queued or checkpoint_passed route state')
        elif row['execution_state'] != {'baseline': 'retained', 'supporting': 'supporting'}[row['execution_lane']]:
            raise ValueError('Baseline/supporting route state does not match lane')
    primary = sorted((r for r in rows if r['execution_lane'] == 'primary'), key=lambda r: int(r['execution_order']))
    if [int(r['execution_order']) for r in primary] != list(range(1, len(primary) + 1)):
        raise ValueError('Primary execution order must be consecutive from 1')
    current = [r for r in rows if r['execution_state'] == 'current']
    if len(current) != 1 or current[0]['execution_lane'] != 'primary':
        raise ValueError('Exactly one primary work item must be explicitly current')
    active = current[0]
    for row in primary:
        before = int(row['execution_order']) < int(active['execution_order'])
        if before and row['execution_state'] != 'checkpoint_passed':
            raise ValueError('Earlier primary checkpoint is not explicitly passed; record any reprioritization')
        if not before and row is not active and row['execution_state'] != 'queued':
            raise ValueError('Later primary work must remain queued')
    return active, primary


def render(rows):
    active, primary = execution_route(rows)
    intro = """# AcademyOS continuation prompt

Generated from `experience-execution.csv`, including its explicit execution lane/order/current state. Do not edit this file directly. Regenerate after every checkpoint with `python3 scripts/design/build_continuation_prompt.py`; the execution validator rejects stale or ambiguous routing. This is a continuation instruction, not new business policy, access authorization or evidence of acceptance.

Reusable instruction: **Continue from the living continuation prompt.**

---

Continue AcademyOS in `/Users/moamenghareeb/AcademyOS`.

Read `AGENTS.md`, `docs/06-delivery/experience-execution.md`, `docs/06-delivery/experience-execution.csv`, `docs/03-design/academy-working-behavior-contract.md`, `docs/06-delivery/academy-working-day-acceptance.md` and the evidence linked by the current row. Recheck working tree, actual source and release. Preserve completed work and concurrent changes.

Start with the explicit current priority below, not the first unfinished EX number or an old next-step sentence in a historical packet. Follow its current next action and scoped dependency gate. Keep the retained baseline and all supporting/open work visible. Advance routing only after recording the declared checkpoint evidence; a routing checkpoint is not whole-finding closure or Owner/security acceptance.

The operating goal is a continuous academy working day: correct workspace → essential current task → bounded likely-task preparation where accepted → safe return/reuse → accurate confirmed updates → interruption/recovery. Shared request ownership and startup/warm-return behaviour are brought forward. Loading every page/database record, changing colours or adding another feature is not a substitute. Code preparation and private data preparation are distinct; do not introduce a duplicate read at hydration/mount/return.

Preserve current server authority, tenant/role/field scope, explicit context choice, dirty input, exact-change/signed review, atomic/idempotent writes and original unknown-operation recovery. WB-P01–P04 are proposed choices until explicitly accepted for their exact capability: no inferred private display TTL, retention, persistence, offline queue, telemetry, role or access grant. Prepare one consolidated decision/changed-state packet; continue independent safe work without repeating accepted policy questions.

Use actual source/PYSA reference and the working-day case map. Record current versus proposed, code/data/authority/draft/recovery owners, initial/repeat/return/save/preparation request budgets and affected-view invalidation. Validate useful task readiness, blank/blocked intervals, preserved input/context, authoritative results and service requests/costs on declared datasets/devices/networks. Measure alongside every batch; fewer requests alone do not prove a better experience. Keep EN/AR, phone/desktop/zoom, denial, concurrency and interruption cases explicit.

After every checkpoint, update the tracker/evidence and affected plan/handoff, maintain actual-component factual HTML where required, regenerate this prompt and run the execution/canonical/review checks. Keep design, implementation, local tests, deployed source, hosted verification, Owner acceptance and independent security separate. If blocked, record the exact decision/evidence/access limitation and safe next action; do not invent approval or silently retire scope. No production launch, service purchase/upgrade or privileged access restoration is included.

"""
    current = '\n'.join([
        f"## Current priority — {active['work_id']}: {active['scope']}", '',
        f"Next action: {active['next_action']}", '',
        f"Scoped dependency gate: {active['dependency_gate']}", '',
        f"Read: `{active['evidence']}`", '',
        '## Ordered primary checkpoints', '',
        *[f"{r['execution_order']}. **{r['work_id']} — {r['scope']}** ({r['execution_state']})." for r in primary], '',
        'Supporting work runs with the affected checkpoint: ' + '; '.join(
            f"{r['work_id']} — {r['scope']}" for r in sorted(
                (r for r in rows if r['execution_lane'] == 'supporting'), key=lambda r: int(r['execution_order']))), '',
        'The order names checkpoint outputs, not a requirement to finish every role/future feature in a parent row before safe dependent work. Detailed gates remain in each row. Private policy choices block dependent behaviour only.', '',
        '## Tracker snapshot', '',
    ])
    fields = [('implementation_status', 'Implementation'), ('local_status', 'Local checks'),
              ('deployment_status', 'Deployment'), ('hosted_status', 'Hosted verification'),
              ('owner_acceptance_status', 'Owner acceptance'), ('independent_security_status', 'Independent security'),
              ('next_action', 'Next action'), ('evidence', 'Evidence')]
    rank = {'baseline': 0, 'primary': 1, 'supporting': 2}
    blocks = []
    for row in sorted(rows, key=lambda r: (rank[r['execution_lane']], int(r['execution_order']))):
        lines = [f"### {row['work_id']} — {row['scope']}", '',
                 f"Routing: {row['execution_lane']} / {row['execution_order']} / {row['execution_state']}.",
                 f"Dependencies: {row['dependencies'] or 'none declared'}.",
                 f"Dependency gate: {row['dependency_gate']}",
                 f"Findings: {row['finding_ids']}.", f"Design: {row['design_status']}.", '']
        lines += [f"- {label}: {row[key]}" for key, label in fields]
        blocks.append('\n'.join(lines))
    return intro + current + '\n' + '\n\n'.join(blocks) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    with TRACKER.open(newline='') as stream:
        expected = render(list(csv.DictReader(stream)))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit('FAIL: continuation prompt stale; run python3 scripts/design/build_continuation_prompt.py')
        print('PASS: continuation prompt matches the execution tracker')
    else:
        OUTPUT.write_text(expected)
        print(f'Updated {OUTPUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
