"""Existing attendance transport readiness, using disposable PG17 only.

No new server contract or hosted connection. Reuses the actual migration harness;
the additional cases establish original-intent replay versus cancellation fencing.
Run: python3 scripts/offline-register/test_boundary.py
"""
import datetime
import hashlib
import json
import runpy
import time
import unittest
import uuid
from pathlib import Path

m = runpy.run_path(str(Path(__file__).resolve().parents[1] / 'attendance-register/test_boundary.py'))
Base, ROOT = m['RegisterBoundary'], m['ROOT']


class OfflineRegisterBoundary(Base):
    def original(self, academy, event, players, op=None, captured='2026-11-03T00:00:00Z'):
        return dict(action='register', academy=academy, event=event,
                    marks=[dict(player=p, status='present' if i == 0 else 'absent', version=0)
                           for i, p in enumerate(players)],
                    captured_at=captured, op=op or str(uuid.uuid4()))

    def query(self, packet):
        # Fictional UUIDs/timestamps are generated by this harness, never user data.
        return (f"select public.a10_register_v1('{packet['academy']}','{packet['event']}',"
                f"'{json.dumps(packet['marks'])}','{packet['captured_at']}','{packet['op']}')")

    def send(self, packet, who='user_owner', ok=True):
        raw = self.sql(self.query(packet), who, ok=ok)
        return json.loads(raw) if ok else raw

    def outcome(self, packet, who='user_owner', ok=True):
        raw = self.sql(f"select public.a10_operation_v1('{packet['academy']}',"
                       f"'{packet['event']}','{packet['op']}')", who, ok=ok)
        return json.loads(raw) if ok else raw

    def count(self, table, event):
        return int(self.sql(f"select count(*) from academy.{table} where event_id='{event}'"))

    def test_offline_01_owner_original_replay_and_exact_receipt(self):
        a, b, ev, x, y = self.pair()
        packet = self.original(a, ev, [x, y])
        encoded = json.dumps(packet, sort_keys=True)
        # Simulate loss of the response; discard it and resend the stored original.
        self.send(packet)
        receipt = self.send(json.loads(encoded))
        self.assertEqual(receipt, dict(kind='register', event=ev, op=packet['op'], count=2))
        self.assertEqual(set(receipt), {'kind', 'event', 'op', 'count'})
        self.assertEqual(self.count('attendance_marks', ev), 2)
        self.assertEqual(self.count('attendance_history', ev), 2)
        self.assertEqual(self.count('attendance_operations', ev), 1)
        self.assertEqual(self.sql(f"select count(*) from academy.audit_events where "
                                 f"academy_id='{a}' and action='attendance.register' "
                                 f"and operation_id='{packet['op']}'"), '1')
        reordered = json.loads(encoded)
        reordered['marks'].reverse()
        self.assertEqual(self.send(reordered), receipt)
        changed = json.loads(encoded)
        changed['captured_at'] = '2026-11-03T00:00:01Z'
        self.assertEqual(self.send(changed), {'error': 'conflict'})
        changed = json.loads(encoded)
        changed['marks'][0]['status'] = 'absent'
        self.assertEqual(self.send(changed), {'error': 'conflict'})
        self.assertEqual(self.outcome(packet), receipt)

    def test_offline_02_fence_and_commit_both_observed_orders(self):
        for commit_first in (True, False):
            with self.subTest(commit_first=commit_first):
                a, b, ev, x, y = self.pair()
                packet = self.original(a, ev, [x, y])
                command = self.caller('user_owner', '/rpc/a10_register_v1') + self.query(packet)
                fence = (self.caller('user_owner', '/rpc/a10_operation_v1') +
                         f"select public.a10_operation_v1('{a}','{ev}','{packet['op']}')")
                # The inherited helper observes pg_blocking_pids before releasing
                # the first transaction; this is not a sleep-only race assertion.
                self.observed_order(command if commit_first else fence,
                                    fence if commit_first else command)
                if commit_first:
                    self.assertEqual(self.outcome(packet)['count'], 2)
                    self.assertEqual(self.send(packet)['count'], 2)
                    self.assertEqual(self.count('attendance_history', ev), 2)
                else:
                    self.assertEqual(self.outcome(packet), {'cancelled': True})
                    self.assertEqual(self.send(packet), {'error': 'conflict'})
                    self.assertEqual(self.count('attendance_marks', ev), 0)
                    self.assertEqual(self.count('attendance_history', ev), 0)
                self.assertEqual(self.count('attendance_operations', ev), 1)

    def test_offline_03_existing_receipt_survives_deadline_but_new_intent_cannot(self):
        a, b, ev, x, y = self.pair()
        self.retime(ev, "clock_timestamp()-interval '25 hours'",
                    "clock_timestamp()-interval '24 hours'+interval '3 seconds'")
        packet = self.original(a, ev, [x, y])
        receipt = self.send(packet)
        self.assertEqual(receipt['count'], 2)
        time.sleep(3.1)
        self.assertFalse(self.roster(a, ev, 'user_owner')['open'])
        self.assertEqual(self.send(packet), receipt)
        self.assertEqual(self.outcome(packet), receipt)
        replacement = {**packet, 'op': str(uuid.uuid4())}
        self.assertEqual(self.send(replacement), {'error': 'window_closed'})
        self.assertEqual(self.count('attendance_history', ev), 2)

    def test_offline_04_unsent_expired_batch_cannot_backdate_or_use_future_device_clock(self):
        a, b, ev, x, y = self.pair()
        self.retime(ev, "clock_timestamp()-interval '26 hours'",
                    "clock_timestamp()-interval '25 hours'")
        for captured in ('2000-01-01T00:00:00Z', '2099-01-01T00:00:00Z'):
            packet = self.original(a, ev, [x, y], captured=captured)
            self.assertEqual(self.send(packet), {'error': 'window_closed'})
        self.assertEqual(self.count('attendance_marks', ev), 0)
        self.assertEqual(self.count('attendance_history', ev), 0)
        self.assertEqual(self.count('attendance_operations', ev), 0)

    def test_offline_05_replay_keeps_current_owner_authority_and_tenant_scope(self):
        a, b, ev, x, y = self.pair()
        packet = self.original(a, ev, [x, y])
        self.send(packet)
        for who in ('user_other_owner', 'user_platform', 'user_guardian', 'user_unknown'):
            self.send(packet, who, ok=False)
            self.outcome(packet, who, ok=False)
        aa, bb = self.academy('user_other_owner')
        self.send({**packet, 'academy': aa}, 'user_other_owner', ok=False)
        self.sql(f"update academy.memberships set status='suspended' "
                 f"where academy_id='{a}' and role='owner'")
        self.send(packet, ok=False)
        self.outcome(packet, ok=False)
        self.assertEqual(self.count('attendance_history', ev), 2)

    def test_offline_06_publication_identity_changes_on_withdraw_republish(self):
        a, b, program, staff, invitation, player, dates = self.fixture()
        first = self.prepare_pub(a, self.pub(a, program, first=dates[0], last=dates[0]))
        self.mutate(a, first, 'activate')
        old = self.schedule(a)['items'][0]['id']
        self.assertEqual(self.roster(a, old, 'user_owner')['count'], 1)
        withdrawal = self.prepare_pub(a, self.pub(a, program, 'withdraw',
                                                  first=dates[0], last=dates[0]))
        self.mutate(a, withdrawal, 'activate')
        self.roster(a, old, 'user_owner', ok=False)
        new_job = self.prepare_pub(a, self.pub(a, program, first=dates[0], last=dates[0]))
        self.mutate(a, new_job, 'activate')
        new = self.schedule(a)['items'][0]['id']
        self.assertNotEqual(old, new)
        self.retime(new)
        old_packet = self.original(a, old, [player])
        self.send(old_packet, ok=False)
        self.assertEqual(self.count('attendance_operations', old), 0)
        self.assertEqual(self.count('attendance_marks', new), 0)
        self.assertEqual(self.send(self.original(a, new, [player]))['count'], 1)
        self.assertEqual(self.sql(f"select count(*) from academy.publication_events "
                                 f"where id='{old}' and published"), '1')

    def test_offline_07_complete_paged_basis_and_saved_version_conflict(self):
        a, b, ev, x, y = self.pair()
        # Test-only fixture adds 119 fictional players before any attendance.
        self.sql(f"insert into academy.players(academy_id,branch_id,display_name,normalized_name)"
                 f"select '{a}','{b}','Synthetic page '||n,'synthetic page '||n "
                 f"from generate_series(1,119)n;"
                 f"insert into academy.publication_rosters select '{ev}',id,display_name "
                 f"from academy.players p where academy_id='{a}' and not exists"
                 f"(select 1 from academy.publication_rosters r where r.event_id='{ev}' "
                 f"and r.player_id=p.id);update academy.publication_events set "
                 f"roster_count=121,capacity=121 where id='{ev}'")
        rows, cursor, pages = [], None, 0
        while True:
            page = self.roster(a, ev, 'user_owner', after=cursor)
            self.assertEqual(page['event'], ev)
            self.assertEqual(page['count'], 121)
            self.assertLessEqual(len(page['players']), 50)
            self.assertLess(len(json.dumps(page, ensure_ascii=False).encode()), 32768)
            self.assertNotIn('rosterVersion', page)
            rows.extend(page['players'])
            pages += 1
            if not page['more']:
                break
            self.assertTrue(page['players'])
            cursor = page['players'][-1]['id']
        self.assertEqual((pages, len(rows), len({r['id'] for r in rows})), (3, 121, 121))
        packet = self.original(a, ev, [x, y])
        self.mark(a, ev, x, 'user_owner', status='absent')
        self.assertEqual(self.send(packet), {'error': 'stale'})
        self.assertEqual(self.count('attendance_marks', ev), 1)
        self.assertEqual(self.history(a, ev, y)['items'], [])


